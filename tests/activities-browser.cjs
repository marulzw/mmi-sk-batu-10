const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const assert = require("node:assert/strict");
const path = require("node:path");
const os = require("node:os");

(async () => {
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  try {
    const context = await browser.newContext({ timezoneId: "Asia/Kuala_Lumpur", viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const page = await context.newPage();
    page.setDefaultTimeout(12000);
    const errors = [];
    page.on("pageerror", (error) => { errors.push(error.message); console.error(error.message); });
    await page.clock.setFixedTime(new Date("2026-11-17T06:30:00Z"));
    await page.route("**/*.cloudfunctions.net/**", (route) => route.request().url().includes("dapatkanJadualWaktu") ? route.continue() : route.abort());
    await page.goto("http://localhost:5173/");
    console.log("App loaded");
    await page.getByRole("button", { name: /Login/ }).click();
    const form = page.getByRole("heading", { name: "Aktiviti Khas / Pengecualian Rekod" }).locator("../..");
    await form.getByLabel("6 Bestari", { exact: true }).waitFor();
    console.log("Classes loaded");
    await form.getByRole("button", { name: "Semua Tahun 6", exact: true }).click();
    const selected = await form.locator('input[type="checkbox"]:checked').count();
    assert.ok(selected > 1);
    await form.getByLabel("Nama Aktiviti / Catatan").fill("Lawatan Sambil Belajar Tahun 6");
    await form.getByRole("button", { name: "Simpan Aktiviti" }).click();
    await form.getByText("Aktiviti berjaya disimpan untuk pratonton local.").waitFor();
    console.log("Full-day activity saved locally");
    await form.getByLabel("Nama Aktiviti / Catatan").fill("Aktiviti Bertindih");
    await form.getByRole("button", { name: "Simpan Aktiviti" }).click();
    await form.getByText(/Aktiviti bertindih dengan pengecualian/).waitFor();
    await page.getByRole("button", { name: "Pemantauan Harian", exact: true }).click();
    await page.getByLabel("Kelas Dipantau").selectOption("6 Bestari");
    await page.getByLabel("Status Slot").selectOption("terlepas");
    await page.getByText("Tiada slot bagi status yang dipilih.").waitFor();
    await page.getByLabel("Status Slot").selectOption("aktiviti");
    assert.ok(await page.locator("tbody tr").count() > 5);
    assert.match(await page.locator("tbody").innerText(), /Lawatan Sambil Belajar Tahun 6/);
    await page.screenshot({ path: path.join(os.tmpdir(), "mmi-activity-monitor-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(os.tmpdir(), "mmi-activity-monitor-mobile.png"), fullPage: true });
    await page.getByRole("button", { name: "Tukar ke mod gelap" }).click();
    await page.screenshot({ path: path.join(os.tmpdir(), "mmi-activity-monitor-dark.png"), fullPage: true, animations: "disabled" });
    await page.getByRole("button", { name: "Analisis", exact: true }).click();
    const analysis = page.getByRole("heading", { name: "6 Bestari", exact: true }).locator("..");
    assert.match(await analysis.innerText(), /Tiada rekod PdP diperlukan hari ini/);
    assert.match(await analysis.innerText(), /0\/0 waktu/);
    await page.getByRole("button", { name: "Laporan Bulanan", exact: true }).click();
    const compile = page.getByRole("heading", { name: "Compile Rekod Bulanan" }).locator("..");
    await compile.getByRole("combobox").nth(0).selectOption("11");
    await compile.getByRole("spinbutton").fill("2026");
    await compile.getByRole("combobox").nth(1).selectOption("6 Bestari");
    const download = page.waitForEvent("download");
    await compile.getByRole("button", { name: "Jana PDF Rekod" }).click();
    await (await download).saveAs(path.join(os.tmpdir(), "mmi-activity-preview.pdf"));
    await page.reload();
    await page.getByRole("button", { name: /Login/ }).click();
    await page.getByRole("heading", { name: "Lawatan Sambil Belajar Tahun 6", exact: true }).waitFor();
    page.on("dialog", (dialog) => dialog.accept());
    await page.getByRole("button", { name: "Batal Pengecualian" }).click();
    await page.getByText("Pengecualian dibatalkan. Rekod guru kekal disimpan.").waitFor();
    await form.getByLabel("6 Bestari", { exact: true }).waitFor();
    await form.getByRole("button", { name: "Semua Tahun 6", exact: true }).click();
    await form.getByLabel("Nama Aktiviti / Catatan").fill("Lawatan Separuh Hari");
    await form.getByLabel("Slot Tertentu", { exact: true }).check();
    await form.getByLabel("7:45 - 8:15", { exact: true }).check();
    await form.getByLabel("8:15 - 8:45", { exact: true }).check();
    await form.getByRole("button", { name: "Simpan Aktiviti" }).click();
    await page.getByRole("button", { name: "Pemantauan Harian", exact: true }).click();
    await page.getByLabel("Kelas Dipantau").selectOption("6 Bestari");
    await page.getByLabel("Status Slot").selectOption("aktiviti");
    assert.equal(await page.locator("article:visible").count(), 2);
    await page.getByLabel("Kelas Dipantau").selectOption("5 Inovatif");
    await page.getByText("Tiada slot bagi status yang dipilih.").waitFor();
    assert.deepEqual(errors, []);
    console.log("PASS: multi-class full day, overlap validation, monitoring, analysis exemption, PDF download, mobile light/dark, persistence, cancel, partial slots, unrelated class unchanged. No login or production writes.");
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
